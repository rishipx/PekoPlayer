// Copies the fonts used by the app from their npm packages (Fontsource) into the project, so the app never contacts
// a font host. Output is committed: public/fonts/*.woff2, public/fonts/LICENSE.txt and src/styles/00-fonts.css.
//
//   npm run fonts:vendor
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = join(root, 'public', 'fonts');
const cssFile = join(root, 'src', 'styles', '00-fonts.css');

// Latin and the scripts the interface is most likely to show; other scripts fall back to system fonts.
const SUBSETS = new Set(['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'greek', 'vietnamese']);

const FAMILIES = [
  { family: 'Inter', pkg: '@fontsource-variable/inter', css: 'wght.css' },
  { family: 'Lora', pkg: '@fontsource-variable/lora', css: 'wght.css' },
  { family: 'Nunito', pkg: '@fontsource-variable/nunito', css: 'wght.css' },
  { family: 'IBM Plex Mono', pkg: '@fontsource/ibm-plex-mono', css: '500.css' },
];

rmSync(fontDir, { recursive: true, force: true });
mkdirSync(fontDir, { recursive: true });

const rules = [];
const licenses = [];
for (const { family, pkg, css } of FAMILIES) {
  const pkgDir = join(root, 'node_modules', ...pkg.split('/'));
  const source = readFileSync(join(pkgDir, css), 'utf8');
  const pattern = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  for (const [, label, body] of source.matchAll(pattern)) {
    const subset = label.replace(
      /^[a-z-]+?-((?:latin|cyrillic|greek|vietnamese|math|symbols|hebrew|arabic)[\w-]*?)-(?:wght|\d{3}|standard|opsz)-normal$/,
      '$1',
    );
    if (!SUBSETS.has(subset) || !/-normal$/.test(label)) continue;
    const field = (name) => body.match(new RegExp(`${name}\\s*:\\s*([^;]+);`))?.[1].trim();
    const file = body.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
    if (!file) throw new Error(`No woff2 file in ${pkg}/${css} (${label})`);
    const name = `${family.toLowerCase().replace(/\s+/g, '-')}-${subset}.woff2`;
    copyFileSync(join(pkgDir, 'files', file), join(fontDir, name));
    rules.push(
      [
        '@font-face {',
        `  font-family: '${family}';`,
        '  font-style: normal;',
        `  font-weight: ${field('font-weight')};`,
        '  font-display: swap;',
        `  src: url(../fonts/${name}) format('woff2');`,
        `  unicode-range: ${field('unicode-range')};`,
        '}',
      ].join('\n'),
    );
  }
  licenses.push(`${family} (${pkg})\n${'-'.repeat(60)}\n${readFileSync(join(pkgDir, 'LICENSE'), 'utf8').trim()}`);
}

if (rules.length === 0) throw new Error('No font faces were generated');
writeFileSync(
  cssFile,
  `/* Self-hosted fonts. Generated by tools/vendor-fonts.mjs; do not edit. */\n\n${rules.join('\n\n')}\n`,
);
writeFileSync(join(fontDir, 'LICENSE.txt'), `${licenses.join('\n\n\n')}\n`);
console.log(`Wrote ${rules.length} @font-face rules to ${cssFile} and font files to ${fontDir}`);
